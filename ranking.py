"""Порядок живой очереди по предмету. Без Telegram и базы, чтобы переиспользовать (например, в веб-панели).

В списке всегда вся группа:
1. Сверху — кто нажал «🙋 Хочу сдать следующее». Среди них раньше тот, у кого меньше сдано,
   при равенстве — жребий.
2. Ниже — все остальные: у кого меньше сдано, тот выше; при равенстве — по алфавиту.
3. В самом низу — кто ещё не зашёл в бота: приоритета у них нет (если только староста
   сам не поставил им 🙋 — тогда они среди желающих).

Жребий — случайное число (lot, random.SystemRandom — случайность операционной системы), одно на
человека, предмет, номер работы и день (таблица lots в db.py). Сортировка по независимым равномерным
числам даёт каждому из N равных одинаковый шанс на любое место. Никакие нажатия его не меняют:
ни «опустить и поднять руку», ни «Сдал» с отменой. В полночь у всех новый — на новой паре равные
тянут заново, и неудача не тянется за человеком. «−1» — только по заявке, которую одобряет староста.
"""
import random
from dataclasses import dataclass, replace

WANT = "🙋"
LOT_BITS = 62  # помещается в INTEGER SQLite

_rnd = random.SystemRandom()

RULES = (
    f"{WANT} <b>Сверху</b> — кто нажал «Хочу сдать следующее». Среди них раньше тот, у кого "
    "<b>меньше сдано</b>, а при равенстве — 🎲 жребий.\n"
    "⬇️ <b>Ниже</b> — все остальные: у кого меньше сдано, тот выше; при равенстве — по алфавиту.\n"
    "❌ <b>В самом низу</b> — кто ещё не зашёл в бота: у них нет приоритета.\n"
    "✅ Сдал работу — жми «Сдал»: счётчик +1, а отметка «хочу сдать» снимается. "
    "Ошибся — «Отменить» в течение минуты, позже — «🙏 Попросить −1» (решает староста).\n"
    "🎲 Жребий не перебросить нажатиями; в полночь он у всех новый.\n"
    "🔁 <b>Обмен</b>: двое по обоюдному согласию меняются местами по предмету — места остальных не двигаются. "
    "Обмен действует, пока кто-то из двоих не сдал; потом оба на своих местах. Обмен — один на каждую работу: "
    "следующий можно после того, как сдано на одну больше."
)


def draw_lot() -> int:
    """Жребий: равномерное случайное целое от 0 до 2^62 − 1."""
    return _rnd.getrandbits(LOT_BITS)


@dataclass
class Row:
    student_id: int
    name: str
    done: int          # сколько работ сдано
    wants: bool        # нажал «хочу сдать следующее»
    lot: int | None    # жребий среди желающих с равным числом сданных
    in_bot: bool = True  # False — ещё не зашёл в бота, без приоритета
    subgroup: int = 0    # 1, 2; 0 — не указана (подгруппа — только фильтр просмотра, на порядок не влияет)
    swapped: bool = False  # стоит на чужом месте по обмену (apply_swaps)


def order(rows: list[Row]) -> list[Row]:
    return sorted(rows, key=lambda r: (
        not r.wants,
        not r.wants and not r.in_bot,
        r.done,
        (r.lot or 0) if r.wants else 0,
        r.name.casefold(),
    ))


def apply_swaps(rows: list[Row], pairs: list[tuple[int, int]]) -> list[Row]:
    """Обмен местами: каждая пара (a, b) меняется местами в уже готовой очереди. Место любого третьего не меняется.
    Обмен «спит» (ничего не меняет), пока двое не в одном блоке очереди — оба с 🙋 или оба без и оба в боте:
    так блоки «хотят сдать» и «остальные» не перемешиваются. У человека не больше одного обмена на предмет
    (это следит db), поэтому цепочек нет."""
    rows = list(rows)
    at = {r.student_id: i for i, r in enumerate(rows)}
    for a, b in pairs:
        if a not in at or b not in at:
            continue
        i, j = at[a], at[b]
        ra, rb = rows[i], rows[j]
        if not (ra.in_bot and rb.in_bot) or ra.wants != rb.wants:
            continue
        rows[i], rows[j] = replace(rb, swapped=True), replace(ra, swapped=True)
        at[a], at[b] = j, i
    return rows
