"""Порядок живой очереди по предмету. Без Telegram и базы, чтобы переиспользовать (например, в веб-панели).

В списке всегда вся группа:
1. Сверху — кто нажал «🙋 Хочу сдать следующее». Среди них раньше тот, у кого меньше сдано,
   при равенстве — жребий.
2. Ниже — все остальные: у кого меньше сдано, тот выше; при равенстве — по алфавиту.
3. В самом низу — кто ещё не зашёл в бота: приоритета у них нет (если только староста
   сам не поставил им 🙋 — тогда они среди желающих).

Жребий — случайное число (lot), которое бросается один раз, когда человек поднимает руку
(random.SystemRandom, случайность операционной системы). Сортировка по независимым равномерным
числам даёт каждому из N равных одинаковый шанс на любое место. Если опустить руку и поднять снова,
число не перебрасывается — иначе можно было бы перекидывать жребий до первого места.
Новое число — только после «Сдал».
"""
import random
from dataclasses import dataclass

WANT = "🙋"
LOT_BITS = 62  # помещается в INTEGER SQLite

_rnd = random.SystemRandom()

RULES = (
    f"{WANT} <b>Сверху</b> — кто нажал «Хочу сдать следующее». Среди них раньше тот, у кого "
    "<b>меньше сдано</b>, а при равенстве — 🎲 жребий.\n"
    "⬇️ <b>Ниже</b> — все остальные: у кого меньше сдано, тот выше; при равенстве — по алфавиту.\n"
    "▫️ <b>В самом низу</b> — кто ещё не зашёл в бота: у них нет приоритета.\n"
    "✅ Сдал работу — жми «Сдал»: счётчик +1, а отметка «хочу сдать» снимается."
)


def draw_lot() -> int:
    """Жребий: равномерное случайное целое от 0 до 2^62 − 1."""
    return _rnd.getrandbits(LOT_BITS)


@dataclass
class Row:
    student_id: int
    name: str
    done: int          # сколько работ сдано
    wants: bool        # нажал «хочу сдать следующее»
    lot: int | None    # жребий среди желающих с равным числом сданных
    in_bot: bool = True  # False — ещё не зашёл в бота, без приоритета
    subgroup: int = 0    # 1, 2; 0 — не указана (подгруппа — только фильтр просмотра, на порядок не влияет)


def order(rows: list[Row]) -> list[Row]:
    return sorted(rows, key=lambda r: (
        not r.wants,
        not r.wants and not r.in_bot,
        r.done,
        (r.lot or 0) if r.wants else 0,
        r.name.casefold(),
    ))
